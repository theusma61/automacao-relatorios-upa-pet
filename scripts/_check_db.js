const path = require('path');
const Database = require(path.join(__dirname, '..', 'node_modules/better-sqlite3'));
const db = new Database('upa_pet.db');
const q = (s, a = []) => db.prepare(s).get(...a);
const c = (s, a = []) => db.prepare(s, a).run();
const nUsers = q('SELECT COUNT(*) n FROM usuarios').n;
const nModels = q('SELECT COUNT(*) n FROM modelos_cirurgicos').n;
const nullCriado = q('SELECT COUNT(*) n FROM usuarios WHERE criado_em IS NULL').n;
const nullModelo = q('SELECT COUNT(*) n FROM modelos_cirurgicos WHERE nome IS NULL OR procedimento IS NULL').n;
const jsonSinonimos = q('SELECT COUNT(*) n FROM modelos_cirurgicos WHERE substr(sinonimos,1,1) = ?', ['[']).n;
